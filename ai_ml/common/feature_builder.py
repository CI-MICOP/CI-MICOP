"""Builds the single claim-level modeling dataset from the 15 raw tables.

Grain: exactly ONE row per Claim_ID (654 rows against the current
dataset export). `claims` is the anchor table; every other table is
either already 1:1 with a claim (verified in the Step 5.1 audit) or is
pre-aggregated to 1:1 by preprocessing.py before being joined here.

Every joined table's non-key columns are prefixed with a short source
tag (see TABLE_PREFIXES) so that columns which exist verbatim in more
than one table - e.g. Document_Mismatch_Indicator appears in BOTH
cross_document_consistency and fraud_risk_analysis - are never silently
overwritten by a merge, and the duplication itself stays visible for
the data-quality report instead of being hidden by a naive join.
"""

from __future__ import annotations

import pandas as pd

from . import preprocessing
from .data_loader import load_all_tables

TABLE_PREFIXES = {
    "vehicles": "veh_",
    "policies": "pol_",
    "customers": "cust_",
    "accidents": "acc_",
    "vehicle_damage": "dmg_",
    "repair_estimates": "est_",
    "cross_document_consistency": "cdc_",
    "fraud_risk_analysis": "frd_",
    "claim_decision_audit": "aud_",
    "surveyor_inspections": "insp_",
    "tp_claims": "tp_",
}

# Columns that are only known once a claim is closed/settled, or that are
# generated by the same downstream process as a candidate target (see
# docs/project_documentation/AI_ML_DATASET_AUDIT.md, Section E). These are
# excluded from every "safe" feature set regardless of which target is
# chosen - they are not pre-decision information.
ALWAYS_LEAKED_COLUMNS = [
    "Final_Decision", "Decision_Date", "Decision_Reason", "Approved_Amount",
    "Claim_Processing_Days", "Repair_Duration_Days",
    "TP_Amount_Claimed", "TP_Claims_Paid", "TP_Awards_Paid", "TP_Expenses_Paid",
    "TP_Interest_Paid", "Wider_Legal_Liability_Amount", "PA_Owner_Driver_Amount",
    "PA_Others_Amount", "Open_Provision_Main", "Open_Provision_Expenses",
    "Open_Provision_Interest", "Closing_Provision_Main", "Closing_Provision_Expenses",
    "Closing_Provision_Interest",
]
# Whole source tables that are entirely post-decision / settlement-time
# and therefore never usable as input features (only as label sources).
ALWAYS_LEAKED_PREFIXES = ["aud_", "tp_"]
# Claim_Status partially echoes Final_Decision's vocabulary (Approved /
# Rejected / Partially Approved are workflow states AND decision labels
# in this dataset) - treat as leakage-adjacent, not a clean pre-decision
# feature, per Section E.
LEAKAGE_ADJACENT_COLUMNS = ["Claim_Status"]
# A column that is only known after repair work is actually completed.
POST_REPAIR_COLUMNS = ["est_Actual_Repair_Days"]

# Candidate targets and the *additional* columns/prefixes that become
# leakage specifically for that target (its own sibling/source-process
# columns), on top of ALWAYS_LEAKED_*. See Section D/E for the reasoning.
TARGET_LEAKAGE_GROUPS = {
    "frd_Fraud_Label": ["frd_"],  # exclude the whole fraud_risk_analysis table as features
    "frd_Risk_Category": ["frd_"],
    "cdc_Overall_Consistency_Status": ["cdc_"],
    "est_Excessive_Claim_Amount_Indicator": ["est_"],
    "Final_Decision": ["aud_"],  # already always-leaked, listed for clarity
}


def build_claim_level_dataset() -> pd.DataFrame:
    """Returns the wide claim-level DataFrame, one row per Claim_ID."""
    tables = load_all_tables()
    claims = tables["claims"]

    result = claims.copy()

    def left_join(df: pd.DataFrame, on: str, prefix: str) -> None:
        nonlocal result
        renamed = df.rename(columns={c: f"{prefix}{c}" for c in df.columns if c not in (on, "Claim_ID")})
        result = result.merge(renamed, on=on, how="left")

    # 1:1 (or 1:1-or-absent) tables - safe to left-join directly.
    left_join(tables["vehicles"], "Vehicle_ID", TABLE_PREFIXES["vehicles"])
    left_join(tables["policies"], "Policy_ID", TABLE_PREFIXES["policies"])
    left_join(tables["customers"], "Customer_ID", TABLE_PREFIXES["customers"])
    left_join(tables["accidents"].drop(columns=["Accident_ID"]), "Claim_ID", TABLE_PREFIXES["accidents"])
    left_join(tables["vehicle_damage"].drop(columns=["Damage_ID", "Vehicle_ID"]), "Claim_ID", TABLE_PREFIXES["vehicle_damage"])
    left_join(tables["repair_estimates"].drop(columns=["Estimate_ID", "Vehicle_ID"]), "Claim_ID", TABLE_PREFIXES["repair_estimates"])
    left_join(tables["cross_document_consistency"].drop(columns=["Consistency_ID"]), "Claim_ID", TABLE_PREFIXES["cross_document_consistency"])
    left_join(tables["fraud_risk_analysis"].drop(columns=["Risk_ID"]), "Claim_ID", TABLE_PREFIXES["fraud_risk_analysis"])
    left_join(tables["claim_decision_audit"].drop(columns=["Audit_ID"]), "Claim_ID", TABLE_PREFIXES["claim_decision_audit"])
    left_join(tables["surveyor_inspections"].drop(columns=["Inspection_ID"]), "Claim_ID", TABLE_PREFIXES["surveyor_inspections"])
    left_join(tables["tp_claims"].drop(columns=["TP_Claim_ID"]), "Claim_ID", TABLE_PREFIXES["tp_claims"])

    # 1:many tables - MUST be aggregated to one row per claim first (see
    # preprocessing.py for why, and the verified cardinalities).
    doc_agg = preprocessing.aggregate_documents(tables["documents"])
    evid_agg = preprocessing.aggregate_evidence(tables["evidence"])
    result = result.merge(doc_agg, on="Claim_ID", how="left")
    result = result.merge(evid_agg, on="Claim_ID", how="left")

    if len(result) != len(claims):
        raise AssertionError(
            f"Claim-level join changed row count: {len(claims)} claims in, {len(result)} rows out. "
            "This means a join fanned out and must be fixed before using this dataset."
        )
    if result["Claim_ID"].duplicated().any():
        raise AssertionError("Claim_ID is no longer unique after the join - aggregation bug.")

    return result


def leaked_columns_for_target(target_column: str, df: pd.DataFrame) -> list[str]:
    """All columns that must be excluded as features when modeling
    `target_column`, given the leakage rules documented above."""
    excluded_prefixes = list(ALWAYS_LEAKED_PREFIXES) + TARGET_LEAKAGE_GROUPS.get(target_column, [])
    excluded = set(ALWAYS_LEAKED_COLUMNS) | {target_column}
    for col in df.columns:
        if any(col.startswith(p) for p in excluded_prefixes):
            excluded.add(col)
    return sorted(excluded)


def safe_feature_columns(target_column: str, df: pd.DataFrame, include_adjacent: bool = False) -> list[str]:
    """Columns considered safe pre-decision features for `target_column`.
    `include_adjacent=True` also keeps leakage-adjacent columns (e.g.
    Claim_Status) for experimentation - off by default."""
    excluded = set(leaked_columns_for_target(target_column, df))
    excluded.update(POST_REPAIR_COLUMNS)
    if not include_adjacent:
        excluded.update(LEAKAGE_ADJACENT_COLUMNS)
    id_columns = {"Claim_ID", "Policy_ID", "Customer_ID", "Vehicle_ID"}
    return [c for c in df.columns if c not in excluded and c not in id_columns]
