"""Data structures for the Step 5.6 surveyor-assignment optimization
experiment.

READ THIS BEFORE USING ANY FIELD BELOW:

The CI-MICOP dataset (654 claims, 20 real surveyors with inspection
records - see docs/project_documentation/ACO_SURVEYOR_ASSIGNMENT.md,
Section 5) does NOT contain the operational information genuine
surveyor-assignment optimization would need: surveyor home/base
coordinates, claim incident coordinates, road distance/travel time,
surveyor specialization, real-time availability, or real-time workload.

Every field on `Claim`/`Surveyor` is tagged REAL or SYNTHETIC below.
REAL fields are read, unmodified, from the actual dataset via
`ai_ml.common.data_loader` (Claim_ID from `claims`, Surveyor_ID from
`surveyor_inspections`). SYNTHETIC fields are generated by
`synthetic_scenario.py` from a fixed random seed and are experimental
assumptions only - never real surveyor/claim attributes.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum


class Priority(str, Enum):
    """SYNTHETIC. No pre-assignment claim-priority field exists in the
    real CI-MICOP schema (the closest real field, Surveyor_Inspections.
    Damage_Severity, is only known AFTER a surveyor has already
    inspected the claim, so it cannot legitimately drive an assignment
    decision made BEFORE inspection). Priority is therefore an
    experimental attribute only."""

    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"


PRIORITY_WEIGHT = {Priority.HIGH: 1.0, Priority.MEDIUM: 0.5, Priority.LOW: 0.0}


class ServiceLevel(str, Enum):
    """SYNTHETIC. Recorded for realism/future use; the Step 5.6 cost
    function does not use this field (kept as a fixed 4-component
    objective per the approved design - see cost_function.py)."""

    STANDARD = "Standard"
    EXPRESS = "Express"


@dataclass(frozen=True)
class Claim:
    claim_id: str  # REAL (from claims.Claim_ID) when use_real_ids=True, else a synthetic label
    location_x: float  # SYNTHETIC - abstract grid unit, NOT a real coordinate
    location_y: float  # SYNTHETIC - abstract grid unit, NOT a real coordinate
    priority: Priority  # SYNTHETIC
    required_service_level: ServiceLevel  # SYNTHETIC, informational only (see ServiceLevel docstring)
    is_real_id: bool = False


@dataclass(frozen=True)
class Surveyor:
    surveyor_id: str  # REAL (from surveyor_inspections.Surveyor_ID) when use_real_ids=True, else synthetic
    location_x: float  # SYNTHETIC
    location_y: float  # SYNTHETIC
    current_workload: int  # SYNTHETIC - starting open-claim count
    maximum_workload: int  # SYNTHETIC - assumed capacity
    availability: bool  # SYNTHETIC
    is_real_id: bool = False


@dataclass
class AssignmentScenario:
    """One reproducible synthetic optimization scenario. `metadata`
    documents exactly which fields are real vs. synthetic and how the
    synthetic ones were generated (see synthetic_scenario.py)."""

    claims: list[Claim]
    surveyors: list[Surveyor]
    seed: int
    metadata: dict = field(default_factory=dict)

    def surveyor_by_id(self) -> dict[str, Surveyor]:
        return {s.surveyor_id: s for s in self.surveyors}

    def claim_by_id(self) -> dict[str, Claim]:
        return {c.claim_id: c for c in self.claims}


@dataclass(frozen=True)
class CostBreakdown:
    distance_cost: float
    workload_cost: float
    priority_cost: float
    total: float


@dataclass(frozen=True)
class Assignment:
    """One claim's outcome. `surveyor_id` is None and `reason` is set
    when Part 6's constraints leave no feasible surveyor - this is
    reported explicitly as UNASSIGNED, never silently dropped or given
    an infeasible surveyor."""

    claim_id: str
    surveyor_id: str | None
    cost: CostBreakdown | None
    reason: str | None = None

    @property
    def is_unassigned(self) -> bool:
        return self.surveyor_id is None


@dataclass
class AssignmentResult:
    strategy: str  # e.g. "greedy_nearest_available", "least_loaded", "aco"
    assignments: list[Assignment]
    runtime_seconds: float
    final_workloads: dict[str, int]  # surveyor_id -> workload after all assignments
    convergence_history: list[float] | None = None  # ACO only: best-so-far cost per iteration
    extra: dict = field(default_factory=dict)
